"""Compile Renderer Slang stages and embed the SPIR-V for desktop and Android."""

import argparse
from pathlib import Path
import struct
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", required=True)
    parser.add_argument("--source-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    stages = {"vert": "Vert", "frag": "Frag", "comp": "Comp"}
    jobs = [(source, "main", stages[source.name.split(".")[-2]], source.stem)
            for source in sorted(args.source_dir.glob("*.*.slang"))]
    for name in ("reproject_light_tile_depth", "build_light_tile_depth_hierarchy", "shadow_occlusion_culling"):
        jobs.append((args.source_dir / (name + ".slang"), "main", "Comp", name))
    source = args.source_dir / "rtReflection.slang"
    for entry_point, stage in (("rayGenMain", "RayGen"), ("missMain", "Miss"),
                               ("missMainShadow", "Miss"), ("closestHitMain", "ClosestHit")):
        jobs.append((source, entry_point, stage, f"{source.stem}.{entry_point}"))
    header = ["// Generated by CompileShaders.py. Do not edit.\n#pragma once\n",
              "#include <lvk/LVK.h>\n#include <cstdint>\n#include <cstddef>\n#include <string_view>\n",
              "namespace RendererShaders {\n"]
    entries = []
    for source, entry_point, stage, output_name in jobs:
        spirv = args.output_dir / (output_name + ".spv")
        # Slang emits the selected entry point as "main" in SPIR-V by default, as LVK's RT pipeline expects.
        subprocess.run([args.compiler, str(source), "-entry", entry_point, "-target", "spirv",
                        "-profile", "spirv_1_5", "-matrix-layout-column-major",
                        "-fvk-use-scalar-layout", "-Wno-39001", "-Wno-41012",
                        "-o", str(spirv)], check=True)
        data = spirv.read_bytes()
        words = struct.unpack(f"<{len(data) // 4}I", data)
        name = output_name.replace(".", "_")
        header.append(f"inline constexpr uint32_t {name}[] = {{\n")
        for i in range(0, len(words), 8):
            header.append("    " + ", ".join(f"0x{word:08x}" for word in words[i:i + 8]) + ",\n")
        header.append("};\n")
        entries.append(f'    {{"{source.name}", "{entry_point}", lvk::Stage_{stage}, {name}, sizeof({name})}},\n')
    if not entries:
        raise RuntimeError("No Renderer Slang stages found")
    header.append("struct Shader { std::string_view name; std::string_view entryPoint; lvk::ShaderStage stage; const uint32_t* data; size_t size; };\n")
    header.append("inline constexpr Shader shaders[] = {\n" + "".join(entries) + "};\n}\n")
    output = args.output_dir / "RendererShaders.h"
    text = "".join(header)
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8")
    else:
        output.touch()
    print(f"Compiled and embedded {len(entries)} Renderer Slang stages")


if __name__ == "__main__":
    main()
